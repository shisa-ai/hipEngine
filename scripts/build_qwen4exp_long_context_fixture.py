#!/usr/bin/env python3
"""Build a long-context case set in the canonical exact-token fixture schema.

The committed canonical fixture
(``benchmarks/fixtures/qwen4exp_canonical_ar_p512_p1024_p4096.json``) was
generated by an ad-hoc process that left no builder behind, so a longer rung
could not be added without re-deriving its construction. This builder derives
it, proves the derivation by reconstructing all twelve committed cases
byte-for-byte, and then applies the identical rule at a longer target.

Derived construction, per case:

1. ``prefix`` = ``<|im_start|>user\\n``
2. ``body`` = the case's source prompts concatenated as
   ``[<id>]\\nuser: <content>\\n\\n`` in ``source_prompt_ids`` order
3. tokenize ``body`` repeated enough times, and truncate the token stream to
   ``target - len(prefix) - len(suffix) - len(newline)``
4. append one ``\\n``, which closes the block that step 3 cut mid-word
5. append ``suffix`` = ``<|im_end|>\\n<|im_start|>assistant\\n``

Step 4 is the non-obvious part: without it the reconstruction reproduces every
committed case except its final token. The truncation in step 3 is at the token
level, so the cut lands mid-word and the trailing newline is what the original
generator emitted.

It performs no measurement and makes no claim.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path

import numpy as np

REPO_ROOT = Path(__file__).resolve().parents[1]
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

from hipengine.loading.gguf import discover_gguf_files, scan_gguf
from hipengine.tokenization.gguf import Qwen35GGUFTokenizer

DEFAULT_MODEL_ROOT = Path(
    "/models/gguf/unsloth-Qwen3.8-Flash-Next-UD-Q4_K_XL/UD-Q4_K_XL"
)
DEFAULT_PROMPTS = REPO_ROOT / "benchmarks" / "prompts" / "mtpbench-code-general-ja.jsonl"
DEFAULT_CANONICAL = (
    REPO_ROOT / "benchmarks" / "fixtures" / "qwen4exp_canonical_ar_p512_p1024_p4096.json"
)
DEFAULT_OUTPUT = REPO_ROOT / "benchmarks" / "fixtures" / "qwen4exp_canonical_ar_p16384.json"

CANONICAL_CATEGORIES = ("code", "general_en", "general_ja", "mixed_ja_en")
DEFAULT_SHAPES = (16384,)


def _sha256_path(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _token_ids_sha256(token_ids: list[int]) -> str:
    return hashlib.sha256(np.asarray(token_ids, dtype="<i8").tobytes()).hexdigest()


def _load_prompt_bodies(path: Path) -> dict[str, dict]:
    rows: dict[str, dict] = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        if not line.strip():
            continue
        row = json.loads(line)
        rows[str(row["id"])] = row
    if not rows:
        raise ValueError(f"no prompts found in {path}")
    return rows


def _block_material(row: dict, prompt_id: str) -> str:
    messages = row.get("messages") or []
    if len(messages) != 1 or str(messages[0].get("role")) != "user":
        raise ValueError(
            f"source prompt {prompt_id!r} must be a single user message"
        )
    return f"[{prompt_id}]\nuser: {messages[0]['content']}\n\n"


def _render(tokenizer, source_prompt_ids: list[str], bodies: dict[str, dict],
            target_tokens: int, *, prefix: list[int], suffix: list[int],
            newline: list[int]) -> list[int]:
    if target_tokens <= len(prefix) + len(suffix) + len(newline):
        raise ValueError("target_tokens is too small for the chat boundaries")
    body = "".join(_block_material(bodies[pid], pid) for pid in source_prompt_ids)
    if not body:
        raise ValueError("source prompts produced empty material")
    body_tokens = target_tokens - len(prefix) - len(suffix) - len(newline)
    # Enough repetitions that the tokenizer never runs out before the target.
    repeats = (body_tokens // 8) + 4
    encoded = tokenizer.encode(body * repeats)
    if len(encoded) < body_tokens:
        raise ValueError(
            f"material is {len(encoded)} tokens, short of the {body_tokens} needed"
        )
    return list(prefix) + list(encoded[:body_tokens]) + list(newline) + list(suffix)


def build(
    model_root: Path,
    prompts_path: Path,
    canonical_path: Path,
    shapes: tuple[int, ...],
    decode_transitions: int,
) -> tuple[dict, dict]:
    gguf = discover_gguf_files(model_root.resolve())[0]
    tokenizer = Qwen35GGUFTokenizer.from_gguf_info(scan_gguf(gguf))
    bodies = _load_prompt_bodies(prompts_path)
    canonical = json.loads(canonical_path.read_text(encoding="utf-8"))

    prefix = [int(t) for t in tokenizer.encode("<|im_start|>user\n")]
    suffix = [int(t) for t in tokenizer.encode("<|im_end|>\n<|im_start|>assistant\n")]
    newline = [int(t) for t in tokenizer.encode("\n")]

    verification = []
    for case in canonical["cases"]:
        reproduced = _render(
            tokenizer, list(case["source_prompt_ids"]), bodies,
            int(case["prompt_tokens"]),
            prefix=prefix, suffix=suffix, newline=newline,
        )
        exact = reproduced == [int(t) for t in case["prompt_token_ids"]]
        verification.append({"id": case["id"], "exact": exact,
                             "tokens": len(reproduced)})
    if not all(row["exact"] for row in verification):
        failed = [row["id"] for row in verification if not row["exact"]]
        raise ValueError(
            "derived construction does not reproduce the committed canonical "
            f"fixture for: {failed}"
        )

    cases = []
    for category in CANONICAL_CATEGORIES:
        source_ids = [
            str(row["id"]) for row in bodies.values()
            if str(row["category"]) == category
        ]
        if not source_ids:
            raise ValueError(f"no source prompts for category {category!r}")
        for shape in shapes:
            ids = _render(
                tokenizer, source_ids, bodies, int(shape),
                prefix=prefix, suffix=suffix, newline=newline,
            )
            if len(ids) != int(shape):
                raise ValueError(f"{category}-p{shape} rendered {len(ids)} tokens")
            cases.append(
                {
                    "id": f"{category}-p{shape}",
                    "category": category,
                    "prompt_tokens": int(shape),
                    "prompt_token_ids": ids,
                    "prompt_token_ids_sha256": _token_ids_sha256(ids),
                    "source_prompt_ids": source_ids,
                    "construction": "canonical_long_context_v1",
                }
            )

    fixture = {
        "schema": 1,
        "kind": "qwen4exp_canonical_ar_exact_token_fixture",
        "name": (
            "Qwen3.8-Flash-Next canonical long-context AR comparison "
            f"({', '.join('p' + str(s) for s in shapes)})"
        ),
        "shapes": [int(s) for s in shapes],
        "categories": list(CANONICAL_CATEGORIES),
        "decode_transitions": int(decode_transitions),
        "source": {
            "path": str(prompts_path.relative_to(REPO_ROOT)),
            "sha256": _sha256_path(prompts_path),
            "construction_basis": {
                "path": str(canonical_path.relative_to(REPO_ROOT)),
                "sha256": _sha256_path(canonical_path),
            },
            "builder": "scripts/build_qwen4exp_long_context_fixture.py",
        },
        "model": dict(canonical.get("model", {})),
        "construction": (
            "Identical construction to the committed p512/p1024/p4096 canonical "
            "fixture, which this builder reconstructs byte-for-byte for all "
            "twelve of its cases before emitting anything. Per category, the "
            "source prompts are concatenated as '[<id>]\\nuser: <content>\\n\\n' "
            "between the fixed '<|im_start|>user\\n' and "
            "'<|im_end|>\\n<|im_start|>assistant\\n' chat boundaries, repeated, "
            "truncated at the token level to the target length minus one, and "
            "closed with a single newline. Engines consume the committed token "
            "arrays directly. The material repeats, so this measures scaling "
            "cost at depth, not long-form quality."
        ),
        "construction_verification": {
            "canonical_cases_reproduced_exactly": len(verification),
            "canonical_cases_total": len(verification),
            "cases": verification,
        },
        "cases": cases,
    }
    return fixture, {"verification": verification, "prefix": prefix,
                     "suffix": suffix, "newline": newline}


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--model-root", type=Path, default=DEFAULT_MODEL_ROOT)
    parser.add_argument("--prompts", type=Path, default=DEFAULT_PROMPTS)
    parser.add_argument("--canonical", type=Path, default=DEFAULT_CANONICAL)
    parser.add_argument("--shapes", type=int, nargs="+", default=list(DEFAULT_SHAPES))
    parser.add_argument("--decode-transitions", type=int, default=128)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    args = parser.parse_args(argv)

    fixture, _ = build(
        args.model_root, args.prompts, args.canonical,
        tuple(args.shapes), args.decode_transitions,
    )
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(fixture, indent=1) + "\n")
    print(
        f"wrote {args.output} "
        f"({len(fixture['cases'])} cases; canonical verification "
        f"{fixture['construction_verification']['canonical_cases_reproduced_exactly']}"
        f"/{fixture['construction_verification']['canonical_cases_total']} exact)"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
