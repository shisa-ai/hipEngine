"""Structural guards for the canonical long-context (p16384) fixture.

The fixture is generated by ``scripts/build_qwen4exp_long_context_fixture.py``,
whose construction rule is only trustworthy because it reconstructs all twelve
committed p512/p1024/p4096 cases byte-for-byte. These tests keep that proof
attached to the artifact and keep the committed token arrays internally
consistent without needing the model or a tokenizer.

A separate tokenizer-dependent test re-derives the cases and is skipped when
the pinned GGUF is not present on this host.
"""

from __future__ import annotations

import hashlib
import json
from pathlib import Path

import numpy as np
import pytest

ROOT = Path(__file__).resolve().parents[1]
FIXTURE = ROOT / "benchmarks" / "fixtures" / "qwen4exp_canonical_ar_p16384.json"
CANONICAL = ROOT / "benchmarks" / "fixtures" / "qwen4exp_canonical_ar_p512_p1024_p4096.json"
MODEL_ROOT = Path("/models/gguf/unsloth-Qwen3.8-Flash-Next-UD-Q4_K_XL/UD-Q4_K_XL")

PREFIX = [248045, 846, 198]
SUFFIX = [248046, 198, 248045, 74455, 198]


@pytest.fixture(scope="module")
def fixture() -> dict:
    return json.loads(FIXTURE.read_text(encoding="utf-8"))


def _ids_sha256(ids) -> str:
    return hashlib.sha256(np.asarray(ids, dtype="<i8").tobytes()).hexdigest()


def test_fixture_covers_every_canonical_category_at_the_target_shape(fixture):
    assert fixture["shapes"] == [16384]
    assert fixture["categories"] == ["code", "general_en", "general_ja", "mixed_ja_en"]
    assert [case["category"] for case in fixture["cases"]] == fixture["categories"]
    for case in fixture["cases"]:
        assert case["prompt_tokens"] == 16384
        assert len(case["prompt_token_ids"]) == 16384
        assert case["id"] == f"{case['category']}-p16384"


def test_committed_token_arrays_match_their_recorded_hashes(fixture):
    for case in fixture["cases"]:
        assert _ids_sha256(case["prompt_token_ids"]) == case["prompt_token_ids_sha256"]


def test_cases_keep_the_fixed_chat_boundaries(fixture):
    for case in fixture["cases"]:
        ids = case["prompt_token_ids"]
        assert ids[: len(PREFIX)] == PREFIX
        assert ids[-len(SUFFIX):] == SUFFIX
        # The block the construction cut mid-word is closed by one newline.
        assert ids[-(len(SUFFIX) + 1)] == 198


def test_fixture_records_an_exact_reconstruction_of_the_canonical_basis(fixture):
    verification = fixture["construction_verification"]
    assert verification["canonical_cases_total"] == 12
    assert verification["canonical_cases_reproduced_exactly"] == 12
    assert all(row["exact"] for row in verification["cases"])
    assert {row["id"] for row in verification["cases"]} == {
        case["id"] for case in json.loads(CANONICAL.read_text(encoding="utf-8"))["cases"]
    }


def test_fixture_pins_the_canonical_basis_it_was_verified_against(fixture):
    basis = fixture["source"]["construction_basis"]
    assert basis["path"].endswith("qwen4exp_canonical_ar_p512_p1024_p4096.json")
    assert hashlib.sha256(
        (ROOT / basis["path"]).read_bytes()
    ).hexdigest() == basis["sha256"]
    assert hashlib.sha256(
        (ROOT / fixture["source"]["path"]).read_bytes()
    ).hexdigest() == fixture["source"]["sha256"]


def test_fixture_declares_its_repetition_limit(fixture):
    # A repeated-material fixture measures scaling cost, not long-form quality.
    assert "not long-form quality" in fixture["construction"]
    for case in fixture["cases"]:
        assert len(set(case["prompt_token_ids"])) < 256


@pytest.mark.skipif(
    not MODEL_ROOT.is_dir(),
    reason="pinned UD-Q4_K_XL GGUF is not present on this host",
)
def test_builder_re_derives_the_committed_cases():
    from scripts.build_qwen4exp_long_context_fixture import build

    rebuilt, _ = build(
        MODEL_ROOT,
        ROOT / "benchmarks" / "prompts" / "mtpbench-code-general-ja.jsonl",
        CANONICAL,
        (16384,),
        128,
    )
    committed = json.loads(FIXTURE.read_text(encoding="utf-8"))
    assert rebuilt["cases"] == committed["cases"]
