def test_dflash2_selector_full_result_matches_torch_reference() -> None:
    data = np.load(FIXTURES / "dflash2_selector_full.npz", allow_pickle=False)
    fixture = load_fixture(FIXTURES / "dflash2_selector_path.json")

    result = candidate_selector_select(
        fixture.inputs["hidden"],
        fixture.inputs["logits"],
        fixture.inputs["anchor_ids"],
        fixture.inputs["predecessor_codebook"],
        fixture.inputs["successor_codebook"],
        fixture.inputs["hidden_projection"],
        top_k=fixture.inputs["top_k"],
    )

    assert np.array_equal(result.path, data["path"])
    # torch.topk(sorted=False) returns the top-k values/indices in unspecified
    # order; numpy sorts descending. Compare value multisets per position.
    assert np.array_equal(np.sort(result.unary, axis=-1), np.sort(data["unary"].astype(np.float32), axis=-1))
    # Scores accumulate rank=8 dot products; allow fp32 rounding in the ordering.
    assert np.allclose(
        np.sort(result.scores, axis=-1),
        np.sort(data["scores"].astype(np.float32), axis=-1),
        atol=1e-5,
    )
    # torch.topk(sorted=False) candidate order is unspecified; compare as sets per position.
    for b in range(data["candidates"].shape[0]):
        for p in range(data["candidates"].shape[1]):
            assert set(result.candidates[b, p].tolist()) == set(data["candidates"][b, p].tolist()), (
                f"candidate set mismatch at ({b},{p})"
            )


