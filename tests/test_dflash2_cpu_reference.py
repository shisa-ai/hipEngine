"""RED tests: DFlash2 CPU reference vs golden fixtures from the z-lab/dflash torch reference.

The golden fixtures were generated by ``scripts/gen_dflash2_cpu_fixtures.py``
running the verbatim reference math (GroupedDynamicCausalConv,
CandidateSelector) from ``~/dflash/dflash/model.py`` @ 07ebd93. These tests
pin the exact contract the native DFlash2 kernels must reproduce.
"""

from __future__ import annotations

from pathlib import Path

import numpy as np
import pytest

from hipengine.kernels.cpu_reference.dflash2 import candidate_selector_select
from hipengine.kernels.cpu_reference.fixtures import load_fixture, run_fixture
from hipengine.kernels.registry import resolve

FIXTURES = Path(__file__).resolve().parent / "fixtures" / "cpu_reference"

CONV_FIXTURES = (
    "dflash2_conv_prepare.json",
    "dflash2_conv_finish.json",
)


@pytest.mark.parametrize("fixture_name", CONV_FIXTURES)
def test_dflash2_grouped_conv_matches_torch_reference(fixture_name: str) -> None:
    fixture = load_fixture(FIXTURES / fixture_name)
    result = run_fixture(fixture)

    assert result.passed, (
        f"{fixture.name}: max_abs={result.max_abs:.3e} max_rel={result.max_rel:.3e} "
        f"vs {fixture.tolerances}"
    )


